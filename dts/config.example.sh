# config.sh —— 环境供给问卷(从本文件复制为 config.sh 后逐项填写)
# 原则:所有"内部才晓得的事实"只进这个文件,不进脚本。
# 每个字段注明:填什么 / 去哪查 / 填错的后果。preflight.sh 会逐项活体检验。

# ============================================================
# 1. 机器与身份(必填)
#    单机部署:脚本直接跑在阶段2复现机器上,不做远程分发。
# ============================================================

# root 执行前缀:每条 root 步实际执行 "${RUN_AS_ROOT} bash -c '...'"
#   - 本身就是 root 跑脚本:留空
#   - sudo 提权:填 "sudo"
RUN_AS_ROOT=""

# 具体用户(数据库用户)执行前缀:其后必须能直接接一条命令。
#   - "sudo -u omm -"   (推荐,omm 换成实际用户)
#   - 留空 = 不切换(仅 mock 用)
# 去哪查:看你们现网装实例的手工步骤里 su 到哪个用户。
# 填错后果:preflight 探活失败,install 用户步全挂。
RUN_AS_USER="sudo -u omm -"

# ============================================================
# 2. 版本包(必填)
# ============================================================

# 包地址模板,{BUILD} 是占位符,装哪个构建就替换成哪个。
#   - 远程 wget:  "http://内部服务器/路径/{BUILD}/GaussDB.tar.gz"
#   - 本地路径(以 / 开头)则直接 cp,mock 测试用这种
# {BUILD} 从哪来:阶段1筛出的单子字段里的版本/构建串。
# 填错后果:preflight 会真去拉这个地址的头几个字节,404 直接红字。
PKG_URL_TEMPLATE="http://CHANGE-ME/{BUILD}/package.tar.gz"

# 校验开关:1=下载后跑 PKG_CHECKSUM_CMD;0=不校验(仅 mock)
PKG_CHECKSUM=1
# 校验命令模板,{PKG} 是下载后的包文件路径。留空则在 PKG_CHECKSUM=1 时只查文件非空。
PKG_CHECKSUM_CMD="sha256sum -c {PKG}.sha256"

# ============================================================
# 3. 安装阶梯(必填)—— root 步与用户步分列,严格先 root 后用户、各按序执行
#    每条是一个 shell 字符串;可用占位符 {BUILD}(构建号)、{PKG}(包路径)。
#    ⚠ 安装脚本不幂等 → 套件保证:成功装过绝不重跑;失败=dirty,下次先清场再全量重装。
# ============================================================
INSTALL_ROOT_STEPS=(
  "bash /opt/CHANGE-ME/pre_install.sh {BUILD}"
  "mkdir -p /opt/gaussdb/install && chown omm /opt/gaussdb/install"
)
INSTALL_USER_STEPS=(
  "bash /opt/CHANGE-ME/install.sh {PKG} {BUILD}"
)

# ============================================================
# 4. 清场(必填)—— 安装不幂等,清场是换版本/重装前的硬前提
#    顺序:先用户步后 root 步,再删 CLEAN_PATHS 声明的路径。
# ============================================================
CLEAN_USER_STEPS=(
  "true"
)
CLEAN_ROOT_STEPS=(
  "bash /opt/CHANGE-ME/uninstall.sh || true"
)
# 只允许删这些前缀之下的路径;根目录/系统目录一律拒绝(preflight 也拦)。
# 单机共享槽:这里填的是"槽位路径"(装谁都放这几处)。
CLEAN_PATHS=(
  "/opt/gaussdb/install"
  "/opt/gaussdb/data"
)

# ============================================================
# 5. 健康检查(必填)—— 装完必须过,过了才记 ready
#    可用占位符 {BUILD}:期望连上的版本串必须对得上,防"装 A 起 B"。
# ============================================================
HEALTH_AS="user"
HEALTH_CHECK_CMD="gsql -d postgres -p 5432 -c 'select version()' | grep -q {BUILD}"

# ============================================================
# 6. 数据目录重置(复现把实例打崩后的分钟级恢复,不整装重装)
#    先用户步后 root 步;{BUILD}/{PKG} 占位符可用。
#    留空 = 该构建只能靠 evict+重装恢复。
# ============================================================
RESET_USER_STEPS=(
  "gs_initdb -D /opt/gaussdb/data/{BUILD}"
)
RESET_ROOT_STEPS=()

# ============================================================
# 7. 运行时目录(一般不用改)
#    注册表/包缓存/锁都在这。registry/<BUILD>/state 是唯一状态真相。
# ============================================================
VAR_HOME="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/var"
